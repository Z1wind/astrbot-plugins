def classify(text: str) -> str | None:
    """返回 crisis / comfort / advance / mixed / None。"""
    t = (text or "").lower()
    if any(w in t for w in CRISIS_WORDS):
        return "crisis"
    hurt = any(w in t for w in HURT_WORDS)
    advance = any(w in t for w in ADVANCE_WORDS)
    if hurt and advance:
        return "mixed"
    if hurt:
        return "comfort"
    if advance:
        return "advance"
    if any(w in t for w in EMOTION_WORDS):
        return "comfort"
    return None


